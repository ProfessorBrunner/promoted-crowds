def _tbl(rs, cols):
    out = ["| " + " | ".join(cols) + " |",
           "|" + "|".join("---" for _ in cols) + "|"]
    for r in rs:
        out.append("| " + " | ".join(str(r.get(c, "")).replace("|", "\\|")
                                     for c in cols) + " |")
    return "\n".join(out)


def _fmt_sci(x):
    """1.52241e-24 -> '1.52 x 10^-24' in the document's notation."""
    e = int(math.floor(math.log10(abs(x))))
    return f"{x / 10 ** e:.2f} \u00d7 10{str(e).translate(_SUP)}"


_SUP = str.maketrans("-0123456789", "\u207b\u2070\u00b9\u00b2\u00b3\u2074\u2075\u2076\u2077\u2078\u2079")


def _prose_numbers(rows):
    """Pull the narrative's figures out of the ledger rows themselves, so section 3
    cannot drift from the table underneath it."""
    out = {}
    for r in rows:
        q = r["quantity"]
        if r["item"] == "P4" and "FLOOR-CORRECTED" in q:
            for lam, key in (("1.6", "fc160"), ("1.75", "fc175"), ("1.9", "fc190")):
                if f"lambda = {lam} " in q:
                    unc = r["interval_on_diff"].split(" (h;")[0].replace("+-", "\u00b1 ")
                    out[key] = f"{r['measured']} {unc}"
        if r["item"] == "A6 multiple testing" and q.startswith("Holm-adjusted endpoint "
                                                              "p-value for P4"):
            out["holmB"] = _fmt_sci(float(r["measured"]))
            tail = r["interval_on_diff"].rsplit("Holm ", 1)[-1]
            out["holmA"] = _fmt_sci(float(tail))
    missing = {"fc160", "fc175", "fc190", "holmB", "holmA"} - set(out)
    assert not missing, f"prose numbers not found in rows: {sorted(missing)}"
    return out


